export const DICTS = { vi, en };
let current = 'vi';

export function getLocale() { return current; }
export function setLocale(l) { current = DICTS[l] ? l : 'vi'; if (typeof document !== 'undefined') document.documentElement.lang = current; }

export function t(key, vars) {
  let s = (DICTS[current] && DICTS[current][key]) ?? vi[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Áp dịch cho DOM tĩnh (gọi khi boot và khi đổi ngôn ngữ) */
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    const s = t(key);
    if (el.tagName === 'H1' && el.querySelector('.offline-badge')) {
      // giữ badge con
      const badge = el.querySelector('.offline-badge');
      el.textContent = s + ' ';
      el.appendChild(badge);
      badge.textContent = t('app.offline');
    } else if (s !== key) el.textContent = s;
  });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
}

/** Định dạng ngày theo ngôn ngữ (dd/MM/yyyy cho vi, en giữ dd/MM/yyyy để tránh nhầm — chỉ đổi nhãn tháng) */
export function monthLabelL(ym) {
  if (!ym) return '';
  const [y, m] = ym.split('-');
  return current === 'en' ? `${m}/${y}` : `T${m}/${y}`;
}
